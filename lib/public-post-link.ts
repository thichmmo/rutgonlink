const numericPostSlugPattern = /^p7-([1-9]\d{4})$/

const AUTO_GENERATED_NUMERIC_TITLES = new Set([
  '',
  'Video Telegram',
  'Ưu đãi hôm nay',
])

export function isNumericPostSlug(slug: string) {
  return numericPostSlugPattern.test(slug)
}

export function numericPostSlug(code: string) {
  return /^[1-9]\d{4}$/.test(code) ? `p7-${code}` : null
}

export function extractNumericPostCode(slug?: string | null): string | null {
  if (!slug) return null
  const match = numericPostSlugPattern.exec(slug)
  return match ? match[1] : null
}

export function isAutoGeneratedNumericTitle(title?: string | null): boolean {
  const trimmed = (title || '').trim()
  if (AUTO_GENERATED_NUMERIC_TITLES.has(trimmed)) return true
  if (/^(?:Video Telegram|Ưu đãi hôm nay)(?:\s*-\s*bản sao)+$/i.test(trimmed)) return true
  if (/^[1-9]\d{4}(?:\s*-\s*bản sao)*$/.test(trimmed)) return true
  return false
}

// Use the 5-digit code itself (e.g. "37325") instead of generic "Video Telegram" on numeric /p7/ posts.
export function resolveNumericPostTitle(title: string | null | undefined, slug?: string | null): string {
  const trimmed = (title || '').trim()
  const code = extractNumericPostCode(slug)
  if (!code) return trimmed
  return isAutoGeneratedNumericTitle(trimmed) ? code : trimmed
}

export function stripUrlProtocol(url?: string | null): string {
  return (url || '').trim().replace(/^https?:\/\//i, '')
}

export function formatPostCreatedAt(input?: string | Date | null): string {
  if (!input) return ''
  const date = input instanceof Date ? input : new Date(input)
  if (Number.isNaN(date.getTime())) return ''
  const parts = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Ho_Chi_Minh',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    hour12: false,
  }).formatToParts(date)
  const get = (type: string) => parts.find((p) => p.type === type)?.value || '00'
  return `${get('hour')}:${get('minute')} ${get('day')}/${get('month')}/${get('year')}`
}

export function getPublicPostPath(slug: string) {
  const match = numericPostSlugPattern.exec(slug)
  // The existing unique slug stores the namespace, without changing old slug routes.
  return match ? `/p7/${match[1]}` : `/${encodeURIComponent(slug)}`
}
